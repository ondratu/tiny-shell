TEST_F(PhotoTest, a_jpeg_is_decoded)
{
    const auto photo =
            tiny::image::load_photo(write("a.jpg", bytes(JPEG, sizeof JPEG)));

    if (!photo) {

        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(photo->width, 16);
    EXPECT_EQ(photo->height, 8);
    EXPECT_TRUE(photo->valid());
    const uint32_t pixel = photo->at(8, 4);
    EXPECT_EQ(pixel >> 24, 0xffu);
    EXPECT_GT((pixel >> 16) & 0xff, 0xf0u); // red, a little off: JPEG is lossy
    EXPECT_LT((pixel >> 8) & 0xff, 0x10u);
    EXPECT_LT(pixel & 0xff, 0x10u);
}

TEST_F(PhotoTest, a_progressive_jpeg_is_decoded)
{
    const auto photo = tiny::image::load_photo(
            write("p.jpg", bytes(PROGRESSIVE_JPEG, sizeof PROGRESSIVE_JPEG)));

    if (!photo) {

        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(photo->width, 8);
    EXPECT_EQ(photo->height, 8);
    EXPECT_GT(photo->at(3, 3) & 0xff, 0xf0u);
}

TEST_F(PhotoTest, the_content_decides_not_the_extension)
{
    const auto photo =
            tiny::image::load_photo(write("noext", bytes(PNG, sizeof PNG)));

    if (!photo) {

        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(photo->width, 2);
    EXPECT_EQ(photo->at(0, 0), 0xffff0000u);
    EXPECT_EQ(photo->at(1, 1), 0x80808080u); // premultiplied, as an icon is
    EXPECT_TRUE(
            tiny::image::load_photo(write("a.jpg", bytes(PNG, sizeof PNG))));
}

TEST_F(PhotoTest, what_is_not_a_png_or_a_jpeg_is_refused)
{
    EXPECT_FALSE(tiny::image::load_photo((root / "missing.jpg").string()));
    EXPECT_FALSE(tiny::image::load_photo(root.string())); // a directory
    EXPECT_FALSE(tiny::image::load_photo(write("empty.jpg", "")));
    EXPECT_FALSE(tiny::image::load_photo(write("text.jpg", "not a picture")));
    EXPECT_FALSE(tiny::image::load_photo(
            write("cut.jpg", bytes(JPEG, sizeof JPEG).substr(0, 100))));
    // BMP and GIF are not built in
    EXPECT_FALSE(tiny::image::load_photo(
            write("a.bmp", "BM" + std::string(60, '\0'))));
    EXPECT_FALSE(tiny::image::load_photo(
            write("a.gif", "GIF89a" + std::string(30, '\0'))));
}

TEST_F(PhotoTest, a_photo_that_needs_too_much_memory_is_refused)
{
    EXPECT_FALSE(tiny::image::load_photo(
            write("big.png", bytes(BIG_PNG, sizeof BIG_PNG))));
    EXPECT_FALSE(tiny::image::load_photo(
            write("big.jpg", bytes(BIG_JPEG, sizeof BIG_JPEG))));
}

TEST_F(PhotoTest, a_file_over_the_limit_is_refused)
{
    const auto file = root / "huge.jpg";
    std::ofstream(file, std::ios::binary) << bytes(JPEG, sizeof JPEG);
    fs::resize_file(file, tiny::image::MAX_PHOTO_FILE + 1);
    EXPECT_FALSE(tiny::image::load_photo(file.string()));
}

TEST(FitPhotoTest, fill_cuts_the_middle_of_a_wider_photo)
{
    const Image photo = rows_of(row({A, B, C, D}), 2); // 4 x 2
    const auto out = tiny::image::fit_photo(photo, 2, 2, Fit::Fill);

    if (!out) {

        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(out->width, 2);
    EXPECT_EQ(out->height, 2);
    EXPECT_EQ(out->at(0, 0), B);
    EXPECT_EQ(out->at(1, 1), C);
}

TEST(FitPhotoTest, fill_cuts_the_middle_of_a_taller_photo)
{
    const Image photo = column({A, B, C, D}); // 1 x 4
    const auto out = tiny::image::fit_photo(photo, 1, 2, Fit::Fill);

    if (!out) {

        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(out->height, 2);
    EXPECT_EQ(out->at(0, 0), B);
    EXPECT_EQ(out->at(0, 1), C);
}

TEST(FitPhotoTest, fill_scales_up_and_down_to_the_size_of_the_screen)
{
    const Image photo = rows_of(row({A, A}), 2);
    const auto up = tiny::image::fit_photo(photo, 6, 3, Fit::Fill);
    if (!up) {
        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(up->width, 6);
    EXPECT_EQ(up->height, 3);
    EXPECT_EQ(up->at(5, 2), A);

    const auto down = tiny::image::fit_photo(photo, 1, 1, Fit::Fill);
    if (!down) {
        FAIL() << "the image was not loaded";
    }
    EXPECT_EQ(down->at(0, 0), A);
}


std::string bytes(const unsigned char* data, size_t size)
{
    return std::string(reinterpret_cast<const char*>(data), size);
}

class PhotoTest : public ::testing::Test {
  protected:
    void SetUp() override
    {
        root = fs::temp_directory_path() /
               ("tiny-photo" + std::to_string(getpid()));
        fs::remove_all(root);
        fs::create_directories(root);
    }

    void TearDown() override { fs::remove_all(root); }

    std::string write(const std::string& name, const std::string& body) const
    {
        const auto file = root / name;
        std::ofstream(file, std::ios::binary) << body;
        return file.string();
    }

    fs::path root;
};

// A picture of one row of the colors.
Image row(std::initializer_list<uint32_t> colors)
{
    Image image;
    image.width = static_cast<int>(colors.size());
    image.height = 1;
    image.pixels.assign(colors.begin(), colors.end());
    return image;
}

// A picture of one column of the colors.
Image column(std::initializer_list<uint32_t> colors)
{
    Image image = row(colors);
    image.height = image.width;
    image.width = 1;
    return image;
}

// The picture of the row repeated in `rows` rows.
Image rows_of(const Image& one, int rows)
{
    Image image = one;
    image.height = rows;
    for (int i = 1; i < rows; ++i) {
        image.pixels.insert(image.pixels.end(), one.pixels.begin(),
                            one.pixels.end());
    }
    return image;
}

